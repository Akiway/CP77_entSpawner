local config = require("modules/utils/core/config")
local utils = require("modules/utils/core/utils")

---The shipped door `.anims` sets, indexed by the rig they declare.
---
---`entAnimatedComponent.animations.gameplay[].animSet` is an ordinary resource ref, so instance data
---can repoint a REGULAR door at a different baked animation. That is the only way to change how far
---a baked door travels: the distance is in the clip, not in a field.
---
---**The rig is the compatibility key, not the folder.** `door_double.anims` and `door_single.anims`
---sit in sibling folders and declare different rigs; `door_gate.anims` and `door_single.anims` sit in
---different folders and share `prop_base_skeleton.rig`. An `.anims` built for another skeleton drives
---bones the door does not have.
---
---A second axis matters as much: the animgraph asks for animations *by name*, so a set that shares
---the rig but is missing a name the current set provides is still a downgrade -- swapping
---`door_single.anims` (19 animations) for `door_gate.anims` (1) keeps the rig and loses everything
---the graph asks for. `getCompatible` requires both.
---
---`data/static/door_anim_rigs.json` is generated by `script/extract_door_anim_rigs.wscript` over the
---loaded archives; re-run it after a game update. Measured on 2.31: 24 sets, 15 distinct rigs, and
---only four groups with more than one member. The useful one is the shutters -- h150 / h250 / h400 /
---h600, all on `int_doors_002__shutters.rig`, all providing `open_slide_vertical`, differing only in
---how far the shutter rolls up.
---@class doorAnimSets
local doorAnimSets = {}

doorAnimSets.storePath = "data/static/door_anim_rigs.json"

---@type table<string, { rig: string, animations: { name: string, duration: number }[] }>?
local sets = nil

---@type table<string, string[]>
local compatibleCache = {}

---@param path any
---@return string
local function normalize(path)
    return utils.normalizePath(path, {
        separator = "backslash",
        lowercase = true,
        emptyAsNil = false
    }) or ""
end

---@return table<string, table>
function doorAnimSets.load()
    if sets then return sets end

    sets = {}
    compatibleCache = {}

    local ok, store = pcall(config.loadFile, doorAnimSets.storePath)
    if not ok or type(store) ~= "table" or type(store.sets) ~= "table" then
        return sets
    end

    -- Keyed by the normalized path so a lookup does not depend on how the ref was spelled in the
    -- .ent (case and separator both vary across shipped files).
    for path, entry in pairs(store.sets) do
        if type(entry) == "table" then
            sets[normalize(path)] = {
                path = path,
                rig = normalize(entry.rig),
                animations = type(entry.animations) == "table" and entry.animations or {}
            }
        end
    end

    return sets
end

---@param path string
---@return table? entry
function doorAnimSets.get(path)
    return doorAnimSets.load()[normalize(path)]
end

---@param entry table?
---@return table<string, boolean>
local function animationNameSet(entry)
    local names = {}
    for _, animation in ipairs(entry and entry.animations or {}) do
        local name = tostring(animation.name or "")
        if name ~= "" then names[name] = true end
    end
    return names
end

---Sets that could replace `path` without the animgraph losing anything: same rig, and every
---animation name the current set provides is also present.
---@param path string
---@return string[] paths Depot paths, sorted, excluding `path` itself
function doorAnimSets.getCompatible(path)
    local key = normalize(path)
    if compatibleCache[key] then return compatibleCache[key] end

    local all = doorAnimSets.load()
    local current = all[key]
    local matches = {}

    if current and current.rig ~= "" then
        local required = animationNameSet(current)

        for otherKey, other in pairs(all) do
            if otherKey ~= key and other.rig == current.rig then
                local provided = animationNameSet(other)
                local complete = true
                for name, _ in pairs(required) do
                    if not provided[name] then
                        complete = false
                        break
                    end
                end
                if complete then table.insert(matches, other.path) end
            end
        end
    end

    table.sort(matches)
    compatibleCache[key] = matches

    return matches
end

---Animation names and durations in one set, for showing what a swap would actually change.
---@param path string
---@return { name: string, duration: number }[]
function doorAnimSets.getAnimations(path)
    local entry = doorAnimSets.get(path)
    return entry and entry.animations or {}
end

---@param path string
---@return string
function doorAnimSets.displayName(path)
    local name = utils.getFileName(tostring(path or ""))
    return name ~= "" and name or tostring(path or "")
end

---@param path string
---@return boolean
function doorAnimSets.isKnown(path)
    return doorAnimSets.get(path) ~= nil
end

---Drop the cache so the next read picks up a regenerated store.
function doorAnimSets.reload()
    sets = nil
    compatibleCache = {}
    doorAnimSets.load()
end

return doorAnimSets
